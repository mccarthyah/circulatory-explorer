"""Embed ATTRIBUTION.txt in a GDScript resource for exported applications.

Run `python3 pipeline/sync_credits.py` after editing ATTRIBUTION.txt. Use --check
in CI to verify the app and standalone notice still match.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / 'scripts' / 'credits_text.gd'


def expected():
    notice = (ROOT / 'ATTRIBUTION.txt').read_text(encoding='utf-8')
    return ('# Generated by pipeline/sync_credits.py from ATTRIBUTION.txt; do not edit.\n'
            'extends RefCounted\n\nconst NOTICE := ' + json.dumps(notice, ensure_ascii=False) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != expected():
            raise SystemExit('Embedded credits are stale: run python3 pipeline/sync_credits.py')
        print('PASS: in-app credits match ATTRIBUTION.txt')
    else:
        TARGET.write_text(expected(), encoding='utf-8')


if __name__ == '__main__':
    main()
